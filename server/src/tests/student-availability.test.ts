function event(socket: Socket, name: string): Promise<unknown> {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => { socket.off(name, done); reject(new Error(`未收到事件 ${name}`)); }, 4000);
    function done(value: unknown) { clearTimeout(timer); resolve(value); }
    socket.once(name, done);
  });
}

