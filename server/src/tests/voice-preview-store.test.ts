import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,mkdir,writeFile,readFile} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {bundledPreviewVoices,createVoicePreviewStore,PREVIEW_TEXT} from '../services/voice-preview-store.js';
const audio=Buffer.from('ID3test-preview');

test('all 218 distributed system previews have valid size and checksum and play without synthesis',async t=>{
 const voices=await bundledPreviewVoices();assert.equal(voices.length,218);assert.ok(voices.every(v=>!v.custom));
 const dir=await mkdtemp(path.join(os.tmpdir(),'preview-builtin-'));t.after(()=>rm(dir,{recursive:true,force:true}));
 const store=createVoicePreviewStore({userRoot:dir});
 for(const voice of voices){const bytes=await store('credential',voice.id,async()=>{throw new Error('must not synthesize');});assert.equal(bytes.length,voice.bytes);assert.equal(createHash('sha256').update(bytes).digest('hex'),voice.sha256);}
});

test('new previews persist across store instances, coalesce and isolate credentials; damaged cache regenerates',async t=>{
 const root=await mkdtemp(path.join(os.tmpdir(),'preview-user-'));t.after(()=>rm(root,{recursive:true,force:true}));
 const options={userRoot:path.join(root,'users'),bundledRoot:path.join(root,'empty')};
 let calls=0;const generate=async()=>{calls++;await new Promise(resolve=>setTimeout(resolve,10));return {audio,text:PREVIEW_TEXT};};
 const store=createVoicePreviewStore(options);
 await Promise.all([store('a','123',generate),store('a','123',generate)]);assert.equal(calls,1);
 await createVoicePreviewStore(options)('a','123',generate);assert.equal(calls,1);
 await store('b','123',generate);assert.equal(calls,2);
 const folder=createHash('sha256').update('a').digest('hex').slice(0,24);
 await writeFile(path.join(options.userRoot,folder,'v1/123.mp3'),'bad');
 await createVoicePreviewStore(options)('a','123',generate);assert.equal(calls,3);
 await assert.rejects(store('a','../123',generate));await assert.rejects(store('a',undefined as never,generate));assert.equal(calls,3);
 await assert.rejects(store('a','456',async()=>{throw new Error('failed');}));
 await store('a','456',generate);assert.equal(calls,4);
 const metadata=await readFile(path.join(options.userRoot,folder,'v1/123.json'),'utf8');assert.equal(metadata.includes('credential'),false);
});

test('user cache takes priority over built-in audio and invalid generated bytes are not persisted',async t=>{
 const root=await mkdtemp(path.join(os.tmpdir(),'preview-priority-'));t.after(()=>rm(root,{recursive:true,force:true}));
 const options={userRoot:path.join(root,'users'),bundledRoot:path.join(root,'bundle')};
 const store=createVoicePreviewStore(options);await store('a','123',async()=>({audio,text:'hello'}));
 await mkdir(path.join(options.bundledRoot,'audio'),{recursive:true});
 const builtin=Buffer.from('ID3different');await writeFile(path.join(options.bundledRoot,'audio/123.mp3'),builtin);
 await writeFile(path.join(options.bundledRoot,'manifest.json'),JSON.stringify({voices:[{id:'123',status:'ready',custom:false,bytes:builtin.length,sha256:createHash('sha256').update(builtin).digest('hex')}]}));
 assert.deepEqual(await createVoicePreviewStore(options)('a','123',async()=>{throw new Error('unneeded');}),audio);
 await assert.rejects(store('a','456',async()=>({audio:Buffer.from('not an mp3'),text:'hello'})));
});
