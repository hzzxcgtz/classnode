'use client';

import type { WorksheetGradeState } from '@/lib/types';

/**
 * 判定那三档的记号（★ 2026-09-29，教师两轮改口后的结论）。
 *
 * ── 形状：**画出来的圆环 + 填充比例** ──────────────────────────────────────
 * ```
 *   全对       ●   整圆填满
 *   部分答对   ◐   左半边填满（垂直平边）
 *   不对       ○   不填，只留描边
 * ```
 * 教师原话（这一版的由来）：「你可以考虑一下『全对』、『部分答对』和『不对』三种状态的
 * 图标，如果都用圆来表示呢？」+ 上一轮「用 1/2 这个符号表示不是很合适，想想看」。
 *
 * 🔴 **三条理由，都是代码里能核的事实**：
 *   ① 「对了多少 = 圆填了多少」不需要认得任何符号 —— 这是给中小学生看的，
 *      而 `½` 要求先认得分数（原话就是「这个符号表示不是很合适」）；
 *   ② **空的圆是中性的** —— 教师 2026-09-27 那一轮反复要的就是「不表扬、也不吓人」
 *      （`✗` → 「用叉叉是不是让学生看了有点害怕？」→ `？` → `−`）。`−` 可以退休了；
 *   ③ 🔴 **字符全部退场** ⇒「居中靠字体度量」那一类缺陷**从结构上消失**。
 *      原来的 `−` 有一笔账记在 `worksheet.module.css`：为了让它视觉居中补了 1px，
 *      而「**它换一个浏览器就偏高了**」（教师实测），因为那 1px 补的是某一个浏览器
 *      字体栈的账。画出来的形状不吃字体度量。
 *
 * 🔴 **颜色走 `currentColor`**：三档的颜色由调用方那一格自己的 `data-tone` 给
 *（绿 / 琥珀 / 红），这里一个十六进制都不写 —— 写死就等于给同一件事留了第二份真源。
 *
 * ⚠️ **一个组件、三档**，不许各画一个：三处各写一份的症状是「同一个状态，两处长得不一样」。
 * 本仓这一类的旧账已经有好几笔（`WrongMark` 的文件头、`blankAnswerStyle` 的注释）。
 *
 * ⚠️ **残留（已告知教师）**：进度那一格的 `◐ 正在写` 也是半圆，两者**可以同时出现在一行**
 *（交过之后又改 ⇒ `state` 回到 draft，而判分结果还在）。这次的画法是描边 + 填充、
 * 颜色也不同，勉强分得开；要根治得把「正在写」也画一遍 —— 那是另一件事，本次不做。
 */
export function ResultGlyph({ state }: { state: WorksheetGradeState }) {
  // 半径 7.5 + 描边 2 的外沿正好落在 18 格的边内（9 ± 8.5）。
  const r = 7.5;
  return (
    <svg width="18" height="18" viewBox="0 0 18 18" aria-hidden="true" style={{ display: 'block' }}>
      {/* 描边圆环恒在：三档都看得见「一个圆」，填充比例才是那一档的信息。
          ⚠️ 先画填充、再画描边？不 —— 描边要压在填充上，否则「填满」那一档的
             外圈会被填充盖掉、看起来比另外两档大一圈。 */}
      {state === 'correct' && <circle cx="9" cy="9" r={r} fill="currentColor" />}
      {state === 'partial' && (
        // 左半边：从正上方沿**逆时针**弧到底（`sweep-flag = 0` ⇒ 走左边），
        // 再直线闭合。写成 `M9 1.5 A7.5 7.5 0 0 0 9 16.5 Z` 就是那条垂直平边的半圆。
        <path d={`M9 ${9 - r} A${r} ${r} 0 0 0 9 ${9 + r} Z`} fill="currentColor" />
      )}
      <circle cx="9" cy="9" r={r} fill="none" stroke="currentColor" strokeWidth="2" />
    </svg>
  );
}
