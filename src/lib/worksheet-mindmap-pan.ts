/**
 * ★ 2026-10-07（教师）：「学生用鼠标点击思维导图的**空白区域**，应该能够取消所有节点的选择状态」。
 *
 * 🔴 为什么必须自己补一句：空白处的**左键**是我们在**捕获阶段**接管的
 *   （平移画布 —— 教师 2026-10-06 要的「和流程图一样，鼠标在空白区域可以移动整个画布」）——
 *   接管时 `stopPropagation()` 了，于是库自己那套「点空白 = 取消选中」**没机会跑**。
 *   ⚠️ 这跟「触屏」无关：那段接管只认鼠标（`pointerType === 'mouse'`），
 *     触屏走的是库自己的手势，点空白本来就会取消选中。
 *
 * ⚠️ 取消选中只在**点击**（按下抬起之间几乎没动）时做，**拖动平移时不做** ——
 *   那是两件事：学生拖画布看一眼，不该顺手把选中弄丢。
 */

/** 按下与抬起之间位移超过这个像素数就算「拖了一下」而不是「点了一下」。 */
export const MINDMAP_CLICK_SLOP_PX = 3;

/**
 * 这一串指针事件算**拖动**吗（从按下那一点量到位移结束那一点）。
 *
 * ⚠️ 量的是**按下点到位移点**的总位移，不是每一次 `pointermove` 的增量 ——
 *   慢慢拖的时候每一步的增量都很小，按增量判会把拖动判成点击。
 * ⚠️ 用曼哈顿距离（`|dx| + |dy|`）而不是欧氏距离：斜着拖 3+3 像素显然动了，
 *   而欧氏距离只有 4.2 —— 阈值只有 3 的时候两者都过，但曼哈顿更贴合「他动了没有」。
 */
export function mindmapDragStarted(
  from: { x: number; y: number },
  to: { x: number; y: number },
): boolean {
  return Math.abs(to.x - from.x) + Math.abs(to.y - from.y) > MINDMAP_CLICK_SLOP_PX;
}
