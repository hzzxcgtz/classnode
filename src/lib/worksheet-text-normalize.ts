/**
 * 粘贴进来的文本「去格式」（★ 2026-10-06，教师在「评分标准」输入框里粘了一份题解之后：
 * 「这里复制进来的文本，格式要去掉」）。
 *
 * 🔴 从 Word / PDF / 网页复制中文时，带进来的**不是内容，是排版**，而它在输入框里长这样：
 *   · 每行前面一段缩进、行尾一堆空格（Word 的段落框）；
 *   · 全角空格 U+3000 与不换行空格 U+00A0（肉眼与普通空格一样，光标却跳两格）；
 *   · 标点**前面**多一个空格 ——「（1 分） ；」（Word 的中西文自动间距，中文里是错的）；
 *   · 冒号/逗号**后面**多一个空格（同上，跟在中文后面时也该去掉）；
 *   · `\r\n` 与连续三四个空行。
 *
 * ⚠️ 分寸：**只去排版，不动内容**。
 *   · 数字与单位之间的空格保留（「满分 4 分」✓）—— 删了会变成「满分4分」，读起来更差；
 *   · 拉丁词之间的空格保留（「AI 评分」✓）；
 *   · 「标点后的空格」只在**后面紧跟中文**时才删（`，AI 评分` 这种混排不动 ✓）。
 *
 * 纯函数 + 幂等：同一个串跑两遍结果一样（所以可以在 `onPaste` 与 `onBlur` 上都用）。
 */

/** 中文（含常见全角标点）字符。 */
const CJK = '\\u4e00-\\u9fff\\u3000-\\u303f\\uff00-\\uffef';
/** 中文标点里「后面不该跟空格」的那些（都在 CJK 区间内，逐字列出更清楚）。 */
const CJK_TRAILING = '，。；：、！？）】」』”’…—';

export function normalizePastedText(raw: string): string {
  let text = raw.replace(/\r\n?/g, '\n');
  // 制表符 / 不换行空格 / 全角空格 ⇒ 普通空格（后面按普通空格统一处理）
  text = text.replace(/[\t\u00a0\u3000]/g, ' ');
  // 行首缩进与行尾空白
  text = text.split('\n').map((line) => line.trim()).join('\n');
  // 连续空格压成一个
  text = text.replace(/ {2,}/g, ' ');
  // 中文标点**前**的空格（Word 的自动间距；「（1 分） ；」就是这一条）
  text = text.replace(new RegExp(` +([${CJK_TRAILING}])`, 'g'), '$1');
  // 开引号/开括号**后**的空格
  text = text.replace(/([（【「『“‘]) +/g, '$1');
  // 中文标点**后**的空格 —— 只在紧跟中文时删（拉丁词之间不动）
  text = text.replace(new RegExp(`([${CJK_TRAILING}]) +(?=[${CJK}])`, 'g'), '$1');
  // 三个以上空行压成一段间隔
  text = text.replace(/\n{3,}/g, '\n\n');
  return text.trim();
}
